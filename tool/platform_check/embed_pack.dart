// Writes integration_test/platform_check/pack.g.dart: cases.json and the
// clip of the platform check as constants, so that the test has them on a
// phone without the app shipping them as assets. Run from the repo after
// changing either file:
//
//   dart run tool/platform_check/embed_pack.dart
//
// test/tool/platform_check_test.dart fails while the two are out of step.
// The perf clip (perf_clip.mp4) is not embedded: desktops read it from the
// repo and phones pick it.
import 'dart:convert';
import 'dart:io';

const packDir = 'integration_test/platform_check';
const casesPath = '$packDir/cases.json';
const generatedPath = '$packDir/pack.g.dart';

/// The text of pack.g.dart for the bytes of cases.json and of the clip.
String packSource(List<int> cases, List<int> clip) =>
    '''
// Generated by tool/platform_check/embed_pack.dart from cases.json and the
// clip beside it. Do not edit; run the tool again.

/// cases.json, base64.
const packJsonBase64 =
    '${base64Encode(cases)}';

/// The clip the engine checks start from, base64.
const clipBase64 =
    '${base64Encode(clip)}';
''';

/// The clip's file name in cases.json.
String clipFileName(List<int> cases) {
  final pack = jsonDecode(utf8.decode(cases)) as Map<String, dynamic>;
  final engine = pack['engine'] as Map<String, dynamic>;
  return (engine['clip'] as Map<String, dynamic>)['file'] as String;
}

void main() {
  final cases = File(casesPath).readAsBytesSync();
  final clip = File('$packDir/${clipFileName(cases)}').readAsBytesSync();
  File(generatedPath).writeAsStringSync(packSource(cases, clip));
  stdout.writeln(
    'Wrote $generatedPath (${cases.length} + ${clip.length} bytes).',
  );
}
