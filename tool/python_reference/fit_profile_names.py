"""Writes lib/core/parsers/fit_profile_names.dart: the names the Python
FIT SDK (garmin_fit_sdk, the one the Python app decodes with) gives to the
enum values the Garmin parser reads. The Dart FIT library returns those
values as numbers; the parser and the dive model use the names.

Run from the Python repo's root with its own interpreter and write the
output into this repo, then `dart format` it:

    cd $PYTHON_REPO
    PYTHONDONTWRITEBYTECODE=1 .venv/bin/python -B \
        $APP_REPO/tool/python_reference/fit_profile_names.py \
        > $APP_REPO/lib/core/parsers/fit_profile_names.dart
"""
import sys
from importlib.metadata import version

from garmin_fit_sdk.profile import Profile

TYPES = ["manufacturer", "garmin_product", "event", "dive_alert", "dive_gas_mode", "dive_gas_status"]


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(part.title() for part in rest)


out = [
    "// GENERATED by tool/python_reference/fit_profile_names.py from the FIT",
    f"// profile of garmin_fit_sdk {version('garmin-fit-sdk')}. Do not edit by hand.",
    "",
    "/// The names the Python FIT SDK gives to enum values, by FIT type. A value",
    "/// that is not listed has no name there either and stays a number.",
    "library;",
    "",
]
for type_name in TYPES:
    values = Profile["types"][type_name]
    out.append(f"/// FIT type `{type_name}`.")
    out.append(f"const Map<int, String> {camel(type_name)}Names = {{")
    for number, name in sorted(((int(k), v) for k, v in values.items())):
        out.append(f"  {number}: '{name}',")
    out.append("};")
    out.append("")
sys.stdout.write("\n".join(out))
